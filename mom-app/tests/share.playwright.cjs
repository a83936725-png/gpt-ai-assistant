// 分享與裂變：邀請連結、分享面板、分享卡、IG 備援、點數、邀請頁、關鍵時刻提醒、好孕島愛心與諮詢鈕。
// Usage: cd mom-app && python3 -m http.server 8080   then   node tests/share.playwright.cjs   [BASE=...]
const { chromium } = require('playwright');
const BASE = process.env.BASE || 'http://localhost:8080/';
const results = []; const errs = [];
const ok = (name, cond, info = '') => results.push({ name, pass: !!cond, info });
(async () => {
  const b = await chromium.launch();
  const ctx = await b.newContext({ viewport: { width: 390, height: 844 }, acceptDownloads: true });
  const p = await ctx.newPage();
  p.on('pageerror', (e) => errs.push(e.message));
  p.on('console', (m) => { if (m.type() === 'error' && !/favicon|Failed to load resource/.test(m.text())) errs.push(m.text()); });
  const opened = [];
  await p.exposeFunction('__opened', (u) => opened.push(u));
  await p.addInitScript(() => { window.open = (u) => { window.__opened(String(u)); return null; }; });
  const S = (f, a) => p.evaluate(f, a);
  await p.goto(`${BASE}?ref=ABC234&from=${encodeURIComponent('小美')}&utm_source=line#/home`); await p.waitForTimeout(500);
  ok('invite link shows who invited you', await p.isVisible('text=小美邀請你一起使用'));
  ok('referral params removed from the address bar', (await S(() => location.search)) === '');
  await p.click('text=先看看範例資料'); await p.waitForTimeout(500);
  await S(() => { App.isNight = () => false; App.applyTheme(); });
  ok('demo data keeps the referral', (await S(() => App.store.state.share.invitedBy)) === 'ABC234');
  const myCode = await S(() => App.store.state.share.code);
  await p.click('.hero-share'); await p.waitForTimeout(1200);
  ok('share sheet: 7 channels (6 apps + 存圖片) + card preview', (await S(() => document.querySelectorAll('.sh-ch').length)) === 7 && !!(await S(() => document.querySelector('.sh-ch[aria-label="存圖片"]'))) && await p.isVisible('.sh-img'));
  await p.click('.sh-line'); await p.waitForTimeout(300);
  const line = decodeURIComponent(opened[opened.length - 1] || '');
  ok('LINE link carries invite code + utm', line.startsWith('https://line.me/R/share?text=') && line.includes(`ref=${myCode}`) && line.includes('utm_source=line') && line.includes('#易家做媽媽'));
  await p.click('.sh-th'); await p.waitForTimeout(200);
  ok('Threads intent link', (opened[opened.length - 1] || '').startsWith('https://www.threads.net/intent/post?text='));
  await p.click('.sh-fb'); await p.waitForTimeout(200);
  ok('Facebook sharer link', (opened[opened.length - 1] || '').startsWith('https://www.facebook.com/sharer/sharer.php?u='));
  const [dl] = await Promise.all([p.waitForEvent('download', { timeout: 8000 }).catch(() => null), p.click('.sh-ig')]);
  ok('IG without Web Share: card downloads (and caption is copied)', !!dl);
  await p.keyboard.press('Escape'); await p.waitForTimeout(300);
  const dim = await S(async () => { const c = App.share.cards()[0]; const blob = await App.share.render(c.spec); const bmp = await createImageBitmap(blob); return [bmp.width, bmp.height]; });
  ok('share card is 1080×1920 (IG Stories)', dim[0] === 1080 && dim[1] === 1920, dim.join('x'));
  const pts = await S(() => App.store.state.share.points);
  ok('sharing earns 好孕點數 (LINE 10 + Threads 10 + FB 10 + IG 20)', pts === 50, String(pts));
  await p.goto(`${BASE}#/invite`); await p.waitForTimeout(600);
  ok('invite page: code, QR, card gallery', (await p.isVisible(`text=${myCode}`)) && await p.isVisible('.inv-qr svg') && (await S(() => document.querySelectorAll('.inv-card').length)) >= 2);
  await p.goto(`${BASE}#/milestones`); await p.waitForTimeout(400);
  await p.click('.ms-item >> nth=0'); await p.waitForTimeout(1500);
  ok('milestone → share prompt', await p.isVisible('.sheet:has-text("新技能")'));
  await p.click('.sheet button:has-text("不要再提醒這類")'); await p.waitForTimeout(300);
  await p.click('.ms-item >> nth=1'); await p.waitForTimeout(1500);
  ok('muted prompts stay quiet', !(await p.isVisible('.sheet:has-text("新技能")')));
  await p.goto(`${BASE}#/island`); await p.waitForTimeout(7500);
  ok('island: collectible heart + counter + brand button', (await p.isVisible('.isl-heart')) && (await p.isVisible('.isl-heart-badge')) && await p.isVisible('.isl-consult'));
  await p.click('.isl-heart', { force: true }); await p.waitForTimeout(300);
  ok('collecting a heart counts', (await S(() => App.store.state.share.hearts.n)) === 1);
  await p.goto(`${BASE}#/home`); await p.waitForTimeout(300);
  ok('island overlay removed elsewhere', !(await p.isVisible('.isl-consult')));
  ok('no page errors', !errs.length, errs.slice(0, 3).join(' | '));
  results.forEach((r) => console.log(`${r.pass ? 'PASS' : 'FAIL'}  ${r.name}${r.info && !r.pass ? `   [${r.info}]` : ''}`));
  console.log(`\n${results.filter((r) => r.pass).length}/${results.length} passed`);
  if (results.some((r) => !r.pass)) process.exitCode = 1;
  await b.close();
})().catch((e) => { console.error('SCRIPT ERROR', e.message); process.exit(1); });
